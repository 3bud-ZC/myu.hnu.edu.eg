export function calculatePaymentSummary(fees: FeeItem[]): PaymentSummary {
  const totalFees = fees.reduce((sum, item) => sum + item.amount, 0);
  const discount = fees.reduce((sum, item) => sum + item.discount, 0);
  const totalPaid = fees.reduce((sum, item) => sum + item.paid, 0);
  const balanceDue = fees.reduce((sum, item) => sum + item.remaining, 0);

  return {
    totalFees,
    feeCount: fees.length,
    discount,
    totalPaid,
    balanceDue,
  };
}

